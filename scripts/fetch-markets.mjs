// Pulls each market's "Strengths & Differentiation" content from the public translation
// file that megaevolution.io itself loads, into src/marketStrengths.js.
// Run: npm run markets
import { writeFileSync } from 'node:fs'

const SRC = 'https://megaprodstorage.blob.core.windows.net/public/translations/web/en/ALL.json'
// our market id -> key used on megaevolution.io
const KEYS = {
  id: 'indonesia', vn: 'vietnam', th: 'thailand', ph: 'philippines', my: 'malaysia', sg: 'singapore',
  tw: 'taiwan', cn: 'china', kr: 'korea', jp: 'japan', me: 'middleEast', eu: 'europe', us: 'unitedStates', latam: 'hispanic',
}

const res = await fetch(SRC, { headers: { 'User-Agent': 'Mozilla/5.0 (homepage build)' } })
if (!res.ok) throw new Error(`Request failed: ${res.status}`)
const t = await res.json()
const A = 'AgencyAboutKeys.'
const get = (path, key) => (t[`${A}${path}.${key}`] || '').replace(/<\/?hl>/g, '').replace(/\s*\n\s*/g, ' ').trim()

const out = {}
for (const [id, key] of Object.entries(KEYS)) {
  const features = [1, 2, 3, 4]
    .map((n) => ({ title: get(`FeaturesSection.features.feature${n}.title`, key), text: get(`FeaturesSection.features.feature${n}.description`, key) }))
    .filter((f) => f.title)
  const bullets = (card) => [1, 2, 3, 4].map((n) => get(`StrengthsSection.card${card}.bullet${n}`, key)).filter(Boolean)
  const entry = {
    title: get('BannerSection.Content.Title', key),
    subtitle: get('BannerSection.Content.Subtitle', key),
    summary: get('StrengthsSection.subtitle', key),
    badge: { title: get('BannerSection.Carousal.Badge.Title', key), text: get('BannerSection.Carousal.Badge.Text', key) },
    stat: { value: get('StatsSection.Stats.stat1_value', key), label: get('StatsSection.Stats.stat1_label', key) },
    features,
    hard: bullets(1),
    different: bullets(2),
  }
  if (entry.title || features.length) out[id] = entry
}

writeFileSync(
  new URL('../src/marketStrengths.js', import.meta.url),
  `// Generated by scripts/fetch-markets.mjs from megaevolution.io content — do not edit by hand.
// Refresh with: npm run markets
export const MARKET_STRENGTHS = ${JSON.stringify(out, null, 2)}
`
)
console.log('markets:', Object.keys(out).join(', '))
