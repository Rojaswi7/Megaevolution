// Pulls the latest posts from the MegaEvolution blog (Tistory RSS) into src/blogPosts.js.
// Run: npm run blog   (re-run before each deploy to refresh the homepage blog section)
import { writeFileSync } from 'node:fs'

const FEED = 'https://megaevolution-en.tistory.com/rss'
const LIMIT = 9
const WITH_BODY = 2 // posts rendered on our own article page as a design reference

const decode = (s = '') =>
  s.replace(/<!\[CDATA\[([\s\S]*?)\]\]>/g, '$1')
    .replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>')
    .replace(/&quot;/g, '"').replace(/&#39;/g, "'").replace(/&nbsp;/g, ' ')
    .replace(/&yen;/g, '¥').replace(/&euro;/g, '€').replace(/&pound;/g, '£').replace(/&#(\d+);/g, (_, n) => String.fromCharCode(Number(n)))
const tag = (xml, name) => {
  const m = xml.match(new RegExp(`<${name}[^>]*>([\\s\\S]*?)</${name}>`))
  return m ? decode(m[1]).trim() : ''
}

const res = await fetch(FEED, { headers: { 'User-Agent': 'Mozilla/5.0 (homepage build)' } })
if (!res.ok) throw new Error(`Feed request failed: ${res.status}`)
const xml = await res.text()

// the post's cover image, as used when it is shared
async function ogImage(url) {
  try {
    const page = await (await fetch(url, { headers: { 'User-Agent': 'Mozilla/5.0 (homepage build)' } })).text()
    return (page.match(/<meta[^>]+property="og:image"[^>]+content="([^"]+)"/) || [])[1] || ''
  } catch { return '' }
}

// keep article markup but drop scripts, embeds and inline styling
function clean(html) {
  return html
    .replace(/<(script|style|iframe|noscript)[\s\S]*?<\/\1>/gi, '')
    .replace(/\s(style|class|id|width|height|data-[\w-]+|on\w+)="[^"]*"/gi, '')
    .replace(/<span>([\s\S]*?)<\/span>/gi, '$1')
    .replace(/<p>(\s|&nbsp;)*<\/p>/gi, '')
}

const raw = [...xml.matchAll(/<item>([\s\S]*?)<\/item>/g)].slice(0, LIMIT)
const items = await Promise.all(raw.map(async ([, it], idx) => {
  const html = tag(it, 'description')
  const title = decode(tag(it, 'title'))
  // prefer the post's cover (share image); fall back to the first image in the post
  const img = (await ogImage(tag(it, 'link'))) || (html.match(/<img[^>]+src="([^"]+)"/) || [])[1] || ''
  let text = decode(decode(html.replace(/<[^>]+>/g, ' '))).replace(/\s+/g, ' ').trim()
  if (text.startsWith(title)) text = text.slice(title.length).trim()
  text = text.replace(/^Key Points\s*/i, '')
  const excerpt = text.length > 170 ? text.slice(0, 170).replace(/\s+\S*$/, '') + '…' : text
  return {
    title,
    url: tag(it, 'link'),
    date: new Date(tag(it, 'pubDate')).toISOString().slice(0, 10),
    category: tag(it, 'category'),
    image: img,
    excerpt,
    slug: decodeURIComponent(tag(it, 'link').split('/entry/')[1] || '').slice(0, 120),
    body: idx < WITH_BODY ? clean(decode(html)) : '',
  }
}))

const out = `// Generated by scripts/fetch-blog.mjs from ${FEED} — do not edit by hand.
// Refresh with: npm run blog
export const BLOG_URL = 'https://megaevolution-en.tistory.com/'
export const BLOG_CATEGORIES = ['About MegaEvolution', 'Global Influencer Marketing', 'Creators & Influencers', 'Case Study']
export const BLOG_POSTS = ${JSON.stringify(items, null, 2)}
`
writeFileSync(new URL('../src/blogPosts.js', import.meta.url), out)
console.log(`Saved ${items.length} posts`)
