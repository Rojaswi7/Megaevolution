// Generates the dotted world map used by the market map:
//   public/map-dots.svg  — one <path>, lazy-loaded as an image (keeps the DOM small)
//   data/mapView.ts      — the projection, so pins can be placed over the image
// Run: npm run map
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)))
const land = feature(topo, topo.objects.land)

// Europe on the left edge, Asia in the middle, the Americas on the right.
const VIEW = { lon0: -25, lon1: 335, lat0: 70, lat1: -44, step: 2 }
let d = ''
let n = 0
for (let lat = VIEW.lat0; lat >= VIEW.lat1; lat -= VIEW.step) {
  for (let lon = VIEW.lon0; lon < VIEW.lon1; lon += VIEW.step) {
    const L = lon > 180 ? lon - 360 : lon
    if (geoContains(land, [L, lat])) { d += `M${+(lon - VIEW.lon0).toFixed(1)} ${+(VIEW.lat0 - lat).toFixed(1)}h0`; n++ }
  }
}
const W = VIEW.lon1 - VIEW.lon0, H = VIEW.lat0 - VIEW.lat1
writeFileSync(new URL('../public/map-dots.svg', import.meta.url),
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="-2 -2 ${W + 4} ${H + 4}"><path d="${d}" fill="none" stroke="#0E0D39" stroke-opacity=".22" stroke-width="1.05" stroke-linecap="round"/></svg>`)
writeFileSync(new URL('../data/mapView.ts', import.meta.url),
  `// Generated by scripts/make-map-dots.mjs — do not edit by hand.\nexport const MAP_VIEW = ${JSON.stringify({ ...VIEW, w: W, h: H })}\n/** Position of a lat/lon on the map image, in percent. */\nexport function project(lat: number, lon: number) {\n  const x = (lon < MAP_VIEW.lon0 ? lon + 360 : lon) - MAP_VIEW.lon0\n  const y = MAP_VIEW.lat0 - lat\n  return { left: ((x + 2) / (MAP_VIEW.w + 4)) * 100, top: ((y + 2) / (MAP_VIEW.h + 4)) * 100 }\n}\n`)
console.log('dots', n)
