// Generates src/mapDots.js — a Pacific-centred dotted map (Asia → US west coast).
// Run: node scripts/make-map-dots.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { feature } from 'topojson-client'
import { geoContains } from 'd3-geo'

const topo = JSON.parse(readFileSync(new URL('../node_modules/world-atlas/land-110m.json', import.meta.url)))
const land = feature(topo, topo.objects.land)

export const VIEW = { lon0: -12, lon1: 250, lat0: 62, lat1: -12, step: 1.7 }
const dots = []
for (let lat = VIEW.lat0; lat >= VIEW.lat1; lat -= VIEW.step) {
  for (let lon = VIEW.lon0; lon <= VIEW.lon1; lon += VIEW.step) {
    const L = lon > 180 ? lon - 360 : lon
    if (geoContains(land, [L, lat])) dots.push([+(lon - VIEW.lon0).toFixed(1), +(VIEW.lat0 - lat).toFixed(1)])
  }
}
const out = `// Generated by scripts/make-map-dots.mjs — do not edit by hand.
export const MAP_VIEW = ${JSON.stringify(VIEW)}
export const MAP_DOTS = ${JSON.stringify(dots)}
`
writeFileSync(new URL('../src/mapDots.js', import.meta.url), out)
console.log('dots', dots.length)
